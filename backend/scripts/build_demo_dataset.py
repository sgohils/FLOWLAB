"""Generate the bundled demo dataset.

The demo analysis is **synthetic**: a corridor simulation is rendered into
image coordinates, written as ordinary trajectories and then pushed through the
*real* analytics pipeline.  That guarantees the demo numbers, the trajectory map
and the simulated scenario all agree with each other, while the UI still labels
everything as a demo dataset.

Run from the repository root::

    python -m backend.scripts.build_demo_dataset
"""

from __future__ import annotations

import json
import math
from typing import Any

from ..analytics.metrics import build_analysis
from ..config import BACKEND_DIR, ensure_directories, settings
from ..models.schemas import Regions, Trajectory, TrajectoryPoint, VideoInfo
from ..simulation.simulator import SimulationRun, simulate

OUTPUT = BACKEND_DIR / "demo" / "sample_analysis.json"
REFERENCE = BACKEND_DIR / "demo" / "sample_reference.json"
DEMO_ID = "demo"

#: Camera geometry of the synthetic scene: a school gate lane seen from above
#: and to the side.  Vehicles drive from the top-left to the bottom-right.
SCENE_START = (0.10, 0.26)
SCENE_SPAN = (0.78, 0.50)
SAMPLE_FPS = 10.0
DURATION = 135.0
#: Time one vehicle takes at the gate.
SERVICE_TIME = 3.2
#: Travel time of an unobstructed vehicle across the corridor.
FREE_FLOW = 11.0
#: Lateral spread of the lanes in image space.
LANE_SPREAD = 0.055
#: Extra per-vehicle offset so 20+ paths stay readable on the map instead of
#: collapsing onto three identical lines.
VEHICLE_SPREAD = 0.075


def dismissal_arrivals() -> list[float]:
    """A realistic school dismissal pattern that also *clears* inside the clip.

    A trickle of early leavers, a dense burst at the gate, then stragglers.
    The timing is chosen so the queue builds, peaks and clears before the clip
    ends: a demo whose queue never discharges would teach nothing.
    Arrival gaps are deterministic (no randomness) so the dataset can be
    regenerated byte-for-byte.
    """
    arrivals: list[float] = []
    moment = 1.0
    # Phase 1: light trickle of early leavers.
    for index in range(4):
        arrivals.append(round(moment, 2))
        moment += 5.0 + 1.5 * math.sin(index)
    # Phase 2: the main burst - gaps collapse to about one second.
    moment += 3.0
    for index in range(16):
        arrivals.append(round(moment, 2))
        moment += 0.9 + 0.8 * abs(math.sin(index * 0.7))
    # Phase 3: stragglers walking out.
    moment += 2.5
    for index in range(6):
        arrivals.append(round(moment, 2))
        moment += 2.6 + 1.4 * math.cos(index * 0.5)
    return [a for a in arrivals if a < DURATION - 6.0]


def vehicle_offsets(vehicle_id: int) -> tuple[int, float]:
    """Lane index and lateral spread for a vehicle id.

    Deterministic (golden-ratio sequence, no RNG) so the trajectories and the
    ground truth are always rendered from the same geometry.
    """
    index = vehicle_id - 1
    lane = (index % 3) - 1  # three visual lanes, one processing gate
    spread = ((index * 0.6180339887) % 1.0 - 0.5) * VEHICLE_SPREAD
    return lane, spread


def project(corridor_position: float, vehicle_id: int) -> tuple[float, float]:
    """Map corridor position (0-1) for a vehicle to image coordinates."""
    lane, spread = vehicle_offsets(vehicle_id)
    return _project(corridor_position, lane, spread)


def _project(corridor_position: float, lane: float, spread: float) -> tuple[float, float]:
    """Map corridor position (0-1) + lane index to image coordinates.

    The lateral offset is tapered towards the gate: a real site funnels every
    vehicle through one gate, and if the demo kept the lanes apart all the way
    to the exit, vehicles would cross the exit line at different points and the
    measured service time would be meaningless.
    """
    taper = max(0.0, 1.0 - corridor_position**3)
    x = (
        SCENE_START[0]
        + SCENE_SPAN[0] * corridor_position
        + (lane * LANE_SPREAD * 0.5 + spread * 0.6) * taper
    )
    y = SCENE_START[1] + SCENE_SPAN[1] * corridor_position + (lane * LANE_SPREAD + spread) * taper
    return (min(0.99, max(0.01, x)), min(0.99, max(0.01, y)))


def build_trajectories() -> tuple[list[Trajectory], object]:
    run = simulate(
        dismissal_arrivals(),
        window_seconds=DURATION,
        free_flow_seconds=FREE_FLOW,
        service_time=SERVICE_TIME,
        channels=1,
        output_step=1.0 / SAMPLE_FPS,
        tail_seconds=30.0,
    )
    trajectories: list[Trajectory] = []
    for index, vehicle in enumerate(run.vehicles):
        points: list[TrajectoryPoint] = []
        previous: tuple[float, float] | None = None
        previous_time = 0.0
        for moment, position in vehicle.path:
            x, y = project(position, vehicle.vehicle_id)
            # A slow sinusoid keeps the paths from looking mathematically
            # perfect while staying deterministic.
            x += 0.0025 * math.sin(moment * 0.6 + index)
            speed = 0.0
            if previous is not None:
                elapsed = moment - previous_time
                if elapsed > 0:
                    speed = math.dist((x, y), previous) / elapsed
            points.append(
                TrajectoryPoint(
                    frame=round(moment * SAMPLE_FPS),
                    time=round(moment, 3),
                    x=round(x, 5),
                    y=round(y, 5),
                    confidence=0.9,
                    bbox=[
                        round(x - 0.035, 5),
                        round(y - 0.045, 5),
                        round(x + 0.035, 5),
                        round(y + 0.045, 5),
                    ],
                    speed=round(speed, 5),
                )
            )
            previous, previous_time = (x, y), moment
        if len(points) < 5:
            continue
        trajectories.append(
            Trajectory(
                vehicle_id=vehicle.vehicle_id,
                vehicle_class="car" if index % 7 else "bus",
                first_seen=points[0].time,
                last_seen=points[-1].time,
                duration=round(points[-1].time - points[0].time, 2),
                path_length=0.0,
                stopped_seconds=0.0,
                queue_seconds=0.0,
                mean_speed=0.0,
                points=points,
            )
        )
    return trajectories, run


def measurement_regions() -> Regions:
    """Regions authored for this synthetic scene.

    The real app *suggests* regions from the trajectories
    (``analytics.suggestions``).  The demo dataset ships with regions drawn for
    its own geometry instead, because a diagonal measurement line would cut
    across the three visual lanes at different points and make the exit line
    scatter the crossing times.  Everything measured downstream is the ordinary
    analytics code.
    """
    return Regions(
        # The gate area: where vehicles pile up and are processed.
        queue=[(0.58, 0.58), (0.99, 0.58), (0.99, 0.99), (0.58, 0.99)],
        # Vehicles pass this line shortly after they appear at the top left.
        # It has to sit to the right of the *lateral spread* of the lanes,
        # otherwise a vehicle in an outer lane starts past the line and is
        # never counted as an arrival.
        entry=[(0.20, 0.0), (0.20, 1.0)],
        # Immediately before the gate, where every lane has converged.
        exit=[(0.87, 0.55), (0.87, 0.99)],
        speed_threshold=settings.speed_threshold,
        min_stop_seconds=settings.min_stop_seconds,
        sample_fps=SAMPLE_FPS,
        auto_detected=False,
    )


def ground_truth(run: SimulationRun, regions: Regions) -> dict[str, Any]:
    """The exact values the synthetic scene was built from.

    The demo trajectories are *rendered from* a corridor simulation, so the
    simulator's own positions are the ground truth for the measurement layer:
    the arrival times, each vehicle's true wait, and the queue length series
    computed with the same rule the analytics use.  Writing them out lets
    ``backend.scripts.validate_against_reference`` check the measurement code
    against known values instead of against itself.
    """
    from ..analytics.simulation_truth import queue_truth

    return queue_truth(run, regions, SAMPLE_FPS, DURATION, project)


def main() -> None:
    ensure_directories(settings)
    trajectories, run = build_trajectories()
    video = VideoInfo(
        filename="demo_school_dismissal.mp4",
        duration=DURATION,
        fps=SAMPLE_FPS,
        width=1280,
        height=720,
        size_bytes=0,
        processed_fps=SAMPLE_FPS,
        frame_count=int(DURATION * SAMPLE_FPS),
        annotated_path=None,
        annotated_url=None,
    )
    analysis = build_analysis(
        analysis_id=DEMO_ID,
        video=video,
        tracks=trajectories,
        regions=measurement_regions(),
        source="demo",
        created_at=1_700_000_000.0,
    )
    analysis.warnings.insert(0, "Demo Dataset - synthetic traffic, not footage from a real site.")
    payload = analysis.model_dump(mode="json")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(payload, separators=(",", ":")), encoding="utf-8")

    # Ground truth for the measurement layer, derived from the generator itself.
    reference = ground_truth(run, analysis.regions)
    reference["regions"] = analysis.regions.model_dump(mode="json")
    reference["clip_source"] = "synthetic - generated by backend/scripts/build_demo_dataset.py"
    reference["permission"] = "generated by this project; no third-party footage involved"
    REFERENCE.write_text(json.dumps(reference, indent=2), encoding="utf-8")
    print(
        f"Wrote {OUTPUT} - {len(analysis.trajectories)} trajectories, "
        f"peak queue {analysis.summary.peak_queue}, "
        f"avg wait {analysis.summary.average_wait_seconds}s, "
        f"throughput {analysis.summary.throughput_per_minute}/min, "
        f"{len(analysis.bottlenecks)} bottlenecks"
    )
    print(f"Wrote {REFERENCE} - ground truth for the measurement layer")


if __name__ == "__main__":
    main()
