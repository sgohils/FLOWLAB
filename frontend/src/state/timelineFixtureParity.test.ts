import { describe, expect, it } from "vitest";
import fixture from "../../../backend/tests/fixtures/timeline_sample.json";
import { positionAt, queueAt } from "./ReplayContext";
import type { TimelinePayload } from "../types";

/**
 * The consumer half of the producer/consumer contract.
 *
 * `build_timeline` (backend) and `positionAt` / `queueAt` (this directory) are
 * two independent implementations of one question - "what did the payload say
 * at t = 1.5?" - and until now nothing had ever run them against each other.
 * The other file in this directory pinned a hand-captured literal, so the
 * backend could change its output and these functions would keep passing
 * against a shape no analysis produces any more: replay would draw vehicles in
 * the wrong place, or report the wrong queue length, with **no failing test**.
 * The interface would just be quietly wrong.
 *
 * `backend/tests/fixtures/timeline_sample.json` is now the contract. It is
 * generated by running the real `build_timeline`, committed, and asserted
 * against by both sides:
 *
 *   - backend/tests/test_timeline.py rebuilds it from the same inputs and fails
 *     if the producer's output moves (the *producer* is locked);
 *   - this file reads the same bytes and fails if these readers disagree with
 *     them at the instants below (the *consumer* is locked).
 *
 * There are no cross-imports. Nothing in `frontend/` imports `backend/` code -
 * only this one JSON file, which is data, and Vite resolves it because the
 * vitest config merges the app's own Vite config (so the resolution is the one
 * the bundler would use). Nothing in `backend/` imports `frontend/`.
 *
 * REGENERATING THE FIXTURE
 * -----------------------
 * If `backend/tests/test_timeline.py::test_committed_fixture_is_exactly_what_the_producer_builds`
 * fails, `build_timeline`'s output changed. That is a behaviour change to be
 * understood, not absorbed:
 *
 *   1. read the diff and name the instants that moved, and by how much;
 *   2. work out why the producer changed (a new rounding rule, a different
 *      resampling step, a changed gap threshold, a reordered key);
 *   3. check the moved instants against the intent this fixture exists to pin -
 *      a position inside a tracking gap must stay *absent*, a parked vehicle
 *      must stay still, the queue series must not collapse to all-zero;
 *   4. only then regenerate the fixture and update the tables below in the same
 *      commit, recording which instants changed and why.
 *
 * Never regenerate the fixture to turn a red test green. It is the contract, and
 * regenerating it to absorb an unexplained change deletes the only evidence
 * that the two implementations had started to disagree.
 */
const PAYLOAD: TimelinePayload = fixture;

/** The one vehicle in the fixture that was genuinely lost. */
const gapped = PAYLOAD.vehicles.find((vehicle) => vehicle.id === 7);

/** Every instant below is asserted in both test files; keep the tables in step. */

function expectPoint(
  actual: { x: number; y: number } | null,
  x: number,
  y: number,
  where: string,
): void {
  expect(actual, `expected a position ${where}, but the payload offered none`).not.toBeNull();
  // Close rather than exact: the values in the table are the mathematically
  // exact answers, and interpolation arithmetic lands a few ULPs away from them.
  // Ten digits is far tighter than any real change to the payload, which rounds
  // to five decimals.
  expect(actual?.x ?? Number.NaN, `x ${where}`).toBeCloseTo(x, 10);
  expect(actual?.y ?? Number.NaN, `y ${where}`).toBeCloseTo(y, 10);
}

describe("the committed fixture, as this side of the contract sees it", () => {
  it("is the payload build_timeline produced for three adversarial tracks", () => {
    expect(PAYLOAD.duration).toBe(4.0);
    expect(PAYLOAD.hz).toBe(4.0);
    expect(PAYLOAD.sampling_fps).toBe(10.0);
    expect(PAYLOAD.gap_threshold_s).toBe(0.25);
    expect(PAYLOAD.track_gaps).toBe(1);
    expect(PAYLOAD.vehicles.map((vehicle) => vehicle.id)).toEqual([3, 7, 11]);
  });

  it("still contains the cases the fixture exists for", () => {
    expect(gapped).toBeDefined();
    expect(gapped?.segments).toHaveLength(2);
    expect(gapped?.segments[0].t.at(0)).toBe(0.0);
    expect(gapped?.segments[0].t.at(-1)).toBe(0.5);
    // The second segment starts off the 0.25 s transport grid, so a reader that
    // assumes a uniform grid for the whole track is caught here.
    expect(gapped?.segments[1].t[0]).toBe(1.1);
    // A parked vehicle: one distinct x across the whole clip.
    const parked = PAYLOAD.vehicles.find((vehicle) => vehicle.id === 11);
    expect(new Set(parked?.segments[0].x).size).toBe(1);
    // The queue series is not accidentally constant, and not accidentally zero.
    const counts = PAYLOAD.queue.map((sample) => sample.q);
    expect(counts[0]).toBe(0);
    expect(Math.max(...counts)).toBe(2);
    expect(new Set(counts).size).toBe(3);
  });
});

describe("positionAt against the committed fixture", () => {
  it("answers null before the first sample and after the last one", () => {
    // Vehicle 3 is tracked 0.0-3.9 s inside a 4 s clip.
    expect(positionAt(PAYLOAD, 3, -0.25)).toBeNull();
    expect(positionAt(PAYLOAD, 3, -0.001)).toBeNull();
    expect(positionAt(PAYLOAD, 3, 4.25)).toBeNull();
    // Vehicle 7 stopped being tracked at 2.0 s; the clip runs to 4.0 s.
    expect(positionAt(PAYLOAD, 7, 2.5)).toBeNull();
    expect(positionAt(PAYLOAD, 7, 3.9)).toBeNull();
  });

  it("returns a stored sample exactly, including on a sample boundary", () => {
    expectPoint(positionAt(PAYLOAD, 3, 0.0), 0.15, 0.5, "vehicle 3 at t=0.0");
    expectPoint(positionAt(PAYLOAD, 3, 0.5), 0.4, 0.5, "vehicle 3 at t=0.5");
    expectPoint(positionAt(PAYLOAD, 3, 3.9), 1.1, 0.5, "vehicle 3 at t=3.9");
    expectPoint(positionAt(PAYLOAD, 7, 1.1), 0.5, 0.8, "vehicle 7 at t=1.1");
  });

  it("interpolates between two samples, on both axes", () => {
    // Halfway between t=0.0 and t=0.25 on vehicle 3: the binary search has to
    // walk a seventeen-sample segment to find that pair.
    expectPoint(positionAt(PAYLOAD, 3, 0.125), 0.2125, 0.5, "vehicle 3 at t=0.125");
    // Halfway between t=1.35 and t=1.6, in the segment that follows the gap.
    expectPoint(positionAt(PAYLOAD, 7, 1.475), 0.6125, 0.8, "vehicle 7 at t=1.475");
  });

  it("reports a parked vehicle as not having moved, and a stopped one as still", () => {
    for (const time of [0, 0.4, 1.4, 2.0, 3.9]) {
      expectPoint(positionAt(PAYLOAD, 11, time), 0.5, 0.5, `vehicle 11 at t=${time}`);
    }
    // Vehicle 3 sits at (0.75, 0.5) from 1.2 s to 3.1 s, so an instant inside
    // the stopped stretch must not show the least drift.
    for (const time of [1.25, 1.625, 2.5, 3.0]) {
      expectPoint(positionAt(PAYLOAD, 3, time), 0.75, 0.5, `vehicle 3 at t=${time}`);
    }
  });

  it("draws nothing inside a tracking gap rather than inventing motion", () => {
    // Vehicle 7 is tracked 0.0-0.5 s and again 1.1-2.0 s. Between the two the
    // position is unknown, and the only honest answer is null - interpolating
    // (0.35, 0.8) -> (0.5, 0.8) across the dropout would be inventing motion
    // across a track that was lost.
    expectPoint(positionAt(PAYLOAD, 7, 0.5), 0.35, 0.8, "vehicle 7 at t=0.5");
    for (const time of [0.625, 0.75, 1.0, 1.05, 1.075, 1.099]) {
      expect(
        positionAt(PAYLOAD, 7, time),
        `vehicle 7 at t=${time} is inside the 0.5-1.1 s dropout`,
      ).toEqual({ x: 0.4125, y: 0.8 });
    }
    expectPoint(positionAt(PAYLOAD, 7, 1.1), 0.5, 0.8, "vehicle 7 at t=1.1");

    // Vehicle 7's two segments do not overlap: an off-by-one in the producer's
    // gap splitting would leave a boundary covered twice, and a reader could
    // then pick either answer at that instant.
    const spans = (gapped?.segments ?? []).map((segment) => [
      segment.t[0],
      segment.t[segment.t.length - 1],
    ]);
    expect(spans).toEqual([
      [0.0, 0.5],
      [1.1, 2.0],
    ]);
    expect(spans[0][1]).toBeLessThan(spans[1][0]);
  });

  it("is null for an unknown vehicle id", () => {
    expect(positionAt(PAYLOAD, 404, 0.5)).toBeNull();
  });
});

describe("queueAt against the committed fixture", () => {
  it("is null before the first sample, and holds the last count after it", () => {
    expect(queueAt(PAYLOAD, -0.2)).toBeNull();
    expect(queueAt(PAYLOAD, -0.001)).toBeNull();
    // The series ends at 3.75 s. Past it the last known count is held, which is
    // what the transport does while the clock runs on past the last sample.
    expect(queueAt(PAYLOAD, 3.75)).toBe(1);
    expect(queueAt(PAYLOAD, 5.0)).toBe(1);
  });

  it("returns the count at a sampled instant", () => {
    expect(queueAt(PAYLOAD, 0)).toBe(0);
    expect(queueAt(PAYLOAD, 0.5)).toBe(1);
    expect(queueAt(PAYLOAD, 1.5)).toBe(1);
    expect(queueAt(PAYLOAD, 1.75)).toBe(2);
    expect(queueAt(PAYLOAD, 3.25)).toBe(2);
  });

  it("picks the nearest sample between two instants", () => {
    expect(queueAt(PAYLOAD, 0.3)).toBe(0); // nearer 0.25 (q=0) than 0.5 (q=1)
    expect(queueAt(PAYLOAD, 0.45)).toBe(1); // nearer 0.5
    expect(queueAt(PAYLOAD, 1.625)).toBe(1); // nearer 1.5 (q=1) than 1.75 (q=2)
    expect(queueAt(PAYLOAD, 1.7)).toBe(2); // nearer 1.75: the count steps up
    expect(queueAt(PAYLOAD, 3.4)).toBe(1); // nearer 3.5: the count steps down
  });

  it("agrees with the peak the backend measured, not with a number of its own", () => {
    const peak = Math.max(...PAYLOAD.queue.map((sample) => sample.q));
    expect(peak).toBe(2);
    expect(queueAt(PAYLOAD, 2.0)).toBe(peak);
  });

  it("is null when the payload carries no queue series at all", () => {
    expect(queueAt({ ...PAYLOAD, queue: [] }, 0.5)).toBeNull();
  });
});